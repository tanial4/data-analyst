def handle_upload(file_obj):
    if file_obj is None:
        return "Upload a file to get started.", gr.update(visible=False)
    try:
        df = load_dataframe(file_obj.name)
        STATE["df"]       = df
        STATE["schema"]   = build_schema(df)
        STATE["filename"] = os.path.basename(file_obj.name)

        num_cols = df.select_dtypes(include="number").columns.tolist()
        cat_cols = df.select_dtypes(include=["object", "category"]).columns.tolist()
        info = (
            f"**{STATE['filename']}** loaded ✓\n\n"
            f"**{len(df):,} rows · {len(df.columns)} columns**\n\n"
            f"**Numeric:** {', '.join(num_cols[:5]) or '—'}\n\n"
            f"**Categorical:** {', '.join(cat_cols[:5]) or '—'}\n\n"
            f"**Null values:** {int(df.isna().sum().sum()):,}"
        )
        return info, gr.update(visible=True)
    except Exception as e:
        return f"Error loading file: {e}", gr.update(visible=False)


def chat_respond(message: str, history: List):
    if STATE["df"] is None:
        history = history + [
            {"role": "user",      "content": message},
            {"role": "assistant", "content": "Please upload a CSV or Excel file first so I can analyze it."},
        ]
        return history, None

    if not message.strip():
        return history, None

    try:
        plan       = get_plan(STATE["schema"], message)
        result     = execute_plan(STATE["df"], plan, message)
        table      = result["table"]
        chart_path = result["chart_path"]
        raw_answer = result["answer"]

        table_md  = table.head(20).to_markdown(index=False) if not table.empty else ""
        narrative = generate_narrative(message, raw_answer, table_md, plan)

        parts = [narrative]
        if not table.empty and len(table) > 1:
            parts.append("\n\n" + table_md)

        history = history + [
            {"role": "user",      "content": message},
            {"role": "assistant", "content": "\n\n".join(parts)},
        ]
        return history, chart_path

    except Exception as e:
        history = history + [
            {"role": "user",      "content": message},
            {"role": "assistant", "content": f"Error during analysis: {str(e)}"},
        ]
        return history, None



def clean_json(raw: str) -> str:
    text = raw.strip().strip("`")
    if text.lower().startswith("json"):
        text = text[4:].strip()
    first = text.find("{");  last = text.rfind("}")
    if first != -1 and last != -1 and last > first:
        text = text[first:last + 1]
    return text


def get_plan(schema: str, question: str) -> Dict[str, Any]:
    full_prompt = (
        f"{PLANNER_PROMPT}\n\nDataset schema:\n{schema}\n\nUser question:\n{question}"
    )
    resp = llm.invoke([HumanMessage(content=full_prompt)])
    raw  = resp.content if isinstance(resp.content, str) else str(resp.content)
    plan = json.loads(clean_json(raw))
    defaults = {
        "operation": "summary", "target_column": None, "groupby_column": None,
        "agg_func": "mean",     "top_n": 10,           "sort_order": "desc",
        "filters": [],          "chart_type": "none",   "chart_x": None,
        "chart_y": None,        "chart_title": "Analysis",
    }
    for k, v in defaults.items():
        plan.setdefault(k, v)
    return plan


def fmt(value: Any) -> str:
    if value is None: return "N/A"
    try:
        if isinstance(value, float):
            if math.isnan(value): return "NaN"
            return f"{value:,.4g}"
        if pd.isna(value): return "NaN"
    except Exception:
        pass
    return str(value)


def pick_num(df: pd.DataFrame) -> Optional[str]:
    cols = df.select_dtypes(include="number").columns.tolist()
    return cols[0] if cols else None


def pick_cat(df: pd.DataFrame) -> Optional[str]:
    cols = df.select_dtypes(include=["object", "category", "bool"]).columns.tolist()
    return cols[0] if cols else None


def apply_filters(df: pd.DataFrame, filters: list) -> pd.DataFrame:
    out = df.copy()
    for f in filters or []:
        col = f.get("column"); op = f.get("operator"); val = f.get("value")
        if col not in out.columns: continue
        try:
            s = out[col]
            if op == "==":         out = out[s == val]
            elif op == "!=":       out = out[s != val]
            elif op == "contains": out = out[s.astype(str).str.contains(str(val), case=False, na=False)]
            else:
                num_val = float(val)
                num_s   = pd.to_numeric(s, errors="coerce")
                if   op == ">":  out = out[num_s > num_val]
                elif op == "<":  out = out[num_s < num_val]
                elif op == ">=": out = out[num_s >= num_val]
                elif op == "<=": out = out[num_s <= num_val]
        except Exception:
            continue
    return out


def execute_plan(df: pd.DataFrame, plan: Dict[str, Any], question: str) -> Dict[str, Any]:
    op       = plan.get("operation", "summary")
    target   = plan.get("target_column")
    groupby  = plan.get("groupby_column")
    agg      = plan.get("agg_func") or "mean"
    top_n    = int(plan.get("top_n") or 10)
    sort_ord = plan.get("sort_order") or "desc"
    filters  = plan.get("filters") or []
    c_type   = plan.get("chart_type", "none")
    c_x      = plan.get("chart_x")
    c_y      = plan.get("chart_y")
    c_title  = plan.get("chart_title") or "Analysis"

    wdf = apply_filters(df, filters)
    if wdf.empty:
        return {"answer": "⚠️ No rows match the applied filters.",
                "table": pd.DataFrame(), "chart_path": None}

    answer       = ""
    result_table = pd.DataFrame()
    chart_path   = None

    # ── SUMMARY ────────────────────────────────────────────
    if op == "summary":
        num_cols = wdf.select_dtypes(include="number").columns.tolist()
        stats = []
        for col in num_cols[:8]:
            s = wdf[col].dropna()
            stats.append({"Column": col, "Count": int(s.count()),
                           "Mean": round(s.mean(), 4), "Median": round(s.median(), 4),
                           "Std": round(s.std(), 4), "Min": round(s.min(), 4),
                           "Max": round(s.max(), 4)})
        result_table = pd.DataFrame(stats) if stats else pd.DataFrame(
            {"Info": [f"Rows: {len(wdf)}", f"Columns: {len(wdf.columns)}",
                      f"Total nulls: {int(wdf.isna().sum().sum())}"]}
        )
        missing = int(wdf.isna().sum().sum())
        answer  = (f"The dataset has **{len(wdf):,} rows** and **{len(wdf.columns)} columns**. "
                   f"Total null values: {missing}. "
                   f"Statistical summary of numeric columns shown below.")
        if c_type == "none" and num_cols:
            c_type = "heatmap"; c_title = "Correlation between numeric variables"
        if c_type == "heatmap":
            chart_path = make_chart("heatmap", wdf, None, None, c_title)

    # ── SCALAR OPERATIONS ──────────────────────────────────
    elif op in ("average", "sum", "count", "min", "max", "median"):
        if not target or target not in wdf.columns:
            target = pick_num(wdf)
        if target is None:
            return {"answer": "Could not find a valid numeric column.",
                    "table": pd.DataFrame(), "chart_path": None}
        num_s = pd.to_numeric(wdf[target], errors="coerce")
        ops_map = {
            "average": ("Mean",   num_s.mean()),
            "sum":     ("Sum",    num_s.sum()),
            "count":   ("Count",  int(num_s.count())),
            "min":     ("Min",    num_s.min()),
            "max":     ("Max",    num_s.max()),
            "median":  ("Median", num_s.median()),
        }
        label, value = ops_map[op]
        result_table = pd.DataFrame({"Metric": [label], "Column": [target], "Value": [value]})
        answer = f"**{label} of '{target}'**: {fmt(value)}"
        if c_type == "none":
            c_type = "histogram" if op in ("average", "median") else "bar"
            c_x, c_y = (target, None) if c_type == "histogram" else ("Metric", "Value")
        chart_path = make_chart(
            c_type,
            wdf[[target]] if c_type in ("histogram", "box") else result_table,
            c_x, c_y, c_title or f"{label} of {target}",
        )

    # ── FULL STATS ─────────────────────────────────────────
    elif op == "full_stats":
        if not target or target not in wdf.columns:
            target = pick_num(wdf)
        if target is None:
            return {"answer": "Could not find a valid numeric column.",
                    "table": pd.DataFrame(), "chart_path": None}
        s = pd.to_numeric(wdf[target], errors="coerce").dropna()
        result_table = pd.DataFrame(list({
            "Count": int(s.count()), "Mean": round(s.mean(), 4),
            "Median": round(s.median(), 4),
            "Mode": round(s.mode().iloc[0], 4) if not s.mode().empty else "N/A",
            "Std Dev": round(s.std(), 4), "Variance": round(s.var(), 4),
            "Min": round(s.min(), 4), "Q1": round(s.quantile(0.25), 4),
            "Q3": round(s.quantile(0.75), 4), "Max": round(s.max(), 4),
            "IQR": round(s.quantile(0.75) - s.quantile(0.25), 4),
            "Skewness": round(s.skew(), 4), "Kurtosis": round(s.kurt(), 4),
        }.items()), columns=["Statistic", "Value"])
        answer     = f"Full statistics for **'{target}'**."
        chart_path = make_chart("box", wdf[[target]], target, target,
                                f"Distribution of {target}")

    # ── TOP N ──────────────────────────────────────────────
    elif op == "top_n":
        sort_col = target if (target and target in wdf.columns) else pick_num(wdf)
        if sort_col is None:
            return {"answer": "No valid column found for sorting.",
                    "table": pd.DataFrame(), "chart_path": None}
        asc          = (sort_ord == "asc")
        result_table = wdf.sort_values(by=sort_col, ascending=asc).head(top_n).copy()
        label        = "lowest" if asc else "highest"
        answer       = f"Top **{top_n}** rows with the **{label}** values in **'{sort_col}'**."
        if c_type == "none":
            cat_col = pick_cat(result_table) or result_table.columns[0]
            num_col = pick_num(result_table)
            if num_col:
                c_type = "bar"; c_x = cat_col; c_y = num_col
        if c_type != "none":
            if not c_x or c_x not in result_table.columns:
                c_x = pick_cat(result_table) or result_table.columns[0]
            if not c_y or c_y not in result_table.columns:
                c_y = pick_num(result_table)
            if c_y:
                chart_path = make_chart(c_type, result_table, c_x, c_y, c_title)

    # ── GROUPBY AGG ────────────────────────────────────────
    elif op == "groupby_agg":
        if not groupby or groupby not in wdf.columns:
            groupby = pick_cat(wdf)
        if groupby is None:
            return {"answer": "No valid categorical column found for grouping.",
                    "table": pd.DataFrame(), "chart_path": None}
        if not target or target not in wdf.columns:
            target = pick_num(wdf)
        if agg not in ("mean", "sum", "count", "min", "max", "median", "std", "var"):
            agg = "count" if target is None else "mean"
        if agg == "count" or target is None:
            grouped    = wdf.groupby(groupby, dropna=False).size().reset_index(name="count")
            metric_col = "count"
        else:
            grouped    = wdf.groupby(groupby, dropna=False)[target].agg(agg).reset_index()
            grouped.columns = [groupby, f"{agg}_{target}"]
            metric_col = f"{agg}_{target}"
        if sort_ord in ("asc", "desc"):
            grouped = grouped.sort_values(metric_col, ascending=(sort_ord == "asc"))
        result_table = grouped.copy()
        answer = (f"**{agg.capitalize()} of '{target or 'count'}'** grouped by **'{groupby}'**. "
                  f"Found **{len(grouped)} groups**.")
        if c_type == "none":
            c_type = "donut" if len(grouped) <= 6 else "bar"
            c_x = groupby; c_y = metric_col
        if c_type != "none":
            if not c_x or c_x not in result_table.columns: c_x = groupby
            if not c_y or c_y not in result_table.columns: c_y = metric_col
            chart_path = make_chart(c_type, result_table, c_x, c_y, c_title)

    # ── DISTRIBUTION ───────────────────────────────────────
    elif op == "distribution":
        if not target or target not in wdf.columns:
            target = pick_num(wdf)
        if target is None:
            return {"answer": "No numeric column found for distribution analysis.",
                    "table": pd.DataFrame(), "chart_path": None}
        s = pd.to_numeric(wdf[target], errors="coerce").dropna()
        result_table = pd.DataFrame({
            "Statistic": ["Count", "Mean", "Median", "Std", "Min", "Max"],
            "Value":     [s.count(), s.mean(), s.median(), s.std(), s.min(), s.max()],
        })
        answer     = (f"Distribution of **'{target}'**: "
                      f"mean = {fmt(s.mean())}, median = {fmt(s.median())}, "
                      f"std = {fmt(s.std())}.")
        chart_path = make_chart("histogram", wdf[[target]], target, None,
                                c_title or f"Distribution of {target}")

    # ── CORRELATION ────────────────────────────────────────
    elif op == "correlation":
        num_cols = wdf.select_dtypes(include="number").columns.tolist()
        x_col = c_x if (c_x and c_x in wdf.columns) else (num_cols[0] if num_cols else None)
        y_col = c_y if (c_y and c_y in wdf.columns) else (num_cols[1] if len(num_cols) >= 2 else None)
        if not x_col or not y_col:
            if len(num_cols) >= 2:
                result_table = wdf[num_cols].corr().round(4)
                answer       = "Correlation matrix between all numeric variables."
                chart_path   = make_chart("heatmap", wdf, None, None,
                                          c_title or "Correlations")
            else:
                return {"answer": "Need at least two numeric columns for correlation.",
                        "table": pd.DataFrame(), "chart_path": None}
        else:
            tmp      = wdf[[x_col, y_col]].apply(pd.to_numeric, errors="coerce").dropna()
            corr_val = tmp[x_col].corr(tmp[y_col])
            strength = ("very strong" if abs(corr_val) > 0.8 else
                        "strong"      if abs(corr_val) > 0.6 else
                        "moderate"    if abs(corr_val) > 0.4 else "weak")
            direction = "positive" if corr_val > 0 else "negative"
            result_table = pd.DataFrame({
                "Variable X": [x_col], "Variable Y": [y_col],
                "Correlation (r)": [round(corr_val, 4)],
                "Interpretation": [f"{strength} {direction}"],
            })
            answer     = (f"Correlation between **'{x_col}'** and **'{y_col}'**: "
                          f"r = **{fmt(corr_val)}** ({strength} {direction}).")
            chart_path = make_chart("scatter", tmp, x_col, y_col,
                                    c_title or f"{x_col} vs {y_col}")

    # ── LIST UNIQUE ────────────────────────────────────────
    elif op == "list_unique":
        if not target or target not in wdf.columns:
            target = pick_cat(wdf)
        if target is None:
            return {"answer": "No categorical column found.",
                    "table": pd.DataFrame(), "chart_path": None}
        uniques      = wdf[target].dropna().astype(str).unique().tolist()
        result_table = pd.DataFrame({target: sorted(uniques)[:200]})
        answer       = f"**'{target}'** has **{len(uniques)} unique values**."
        if c_type == "none" and len(uniques) <= 15:
            counts     = wdf[target].value_counts().head(12).reset_index()
            counts.columns = [target, "count"]
            c_type     = "donut" if len(counts) <= 7 else "bar"
            chart_path = make_chart(c_type, counts, target, "count",
                                    f"Distribution of {target}")
    else:
        answer = f"Operation '{op}' not recognized."

    return {"answer": answer, "table": result_table, "chart_path": chart_path}

"""##### **LLM Narrator**"""

def generate_narrative(question: str, answer: str, table_md: str, plan: Dict) -> str:
    prompt = f"""You are an expert data analyst. Respond clearly and directly in English.

The user asked: "{question}"

Analysis result:
{answer}

Data (first rows):
{table_md[:1500]}

Operation: {plan.get('operation')} | Chart generated: {plan.get('chart_type')}

Write a NATURAL response in 3-4 sentences that:
1. Directly answers the question with the most relevant concrete data points.
2. Highlights the most interesting insight or pattern found.
3. Briefly suggests a useful follow-up question.

Do not repeat the full table. Avoid excessive markdown. Respond like an expert analyst talking to a colleague.

IMPORTANT — Number formatting rules (follow these strictly):
- NEVER use scientific notation (e.g. never write 1.23e+06 or 4.5e-3).
- Always write numbers in full: 1,230,000 instead of 1.23e+06.
- Use commas as thousands separators for large numbers: 1,450,320.
- Round decimals to 2 places maximum: 3.14, not 3.14159265.
- For very small numbers, use decimals: 0.0045, not 4.5e-3.
- For percentages, always include the % symbol: 23.4%, not 0.234.
- For currency, include the appropriate symbol if inferrable from context."""

    resp = llm.invoke([HumanMessage(content=prompt)])
    return resp.content if isinstance(resp.content, str) else str(resp.content)

